// Generates the ABAP that prepares the terms and conditions (heading + numbered rows) from the legacy export, so that the
// layout prints ONE table (GT_TERMS) and ONE heading (GV_TERMS_TITLE) instead of three stacked variants with scripts.
//   node terms_gen.mjs <repo>     writes tools/zmmcg_po_sf/terms_extra.abap
// Rules reproduced from the legacy form: which folder applies (table condition V_FLAG, folder condition V_BSART), print language
// (French for ZPOL / ZPOS, English for ZPOI, otherwise the logon language), French text falls back to English when the node has none,
// SAPscript paragraphs (blank format = continuation joined with a blank, '=' joined, other = new line, /* and /: skipped).
// ABAP style (user standards): DIL names (gv_ / gt_ / lv_), ABAP 7.4+ (COND, VALUE, string templates).
import fs from 'node:fs';
import path from 'node:path';
import { loadModel, isDead, liveItems } from './model.mjs';

const repo = process.argv[2];
const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const M = loadModel(path.join(repo, 'vernasofttechie-zmmcg_po_sf/zmmcg_po_sf.xml'));

function find(n, pred) { if (pred(n)) return n; for (const c of n.children) { const r = find(c, pred); if (r) return r; } return null; }

// ---- conditions -> ABAP
const operand = (o) => (/^'.*'$/.test(o) ? `'${o.slice(1, -1).replace(/'/g, "''")}'` : (o.toUpperCase() === 'SY-LANGU' ? 'gv_langu' : o.toLowerCase()));
function condOne(items) {
  const parts = [];
  items.forEach((i, ix) => parts.push((ix ? ` ${i.lop === 'OR' ? 'OR' : 'AND'} ` : '') + `${operand(i.op1)} ${i.cop} ${operand(i.op2)}`));
  return parts.join('');
}
function abapCond(condArrays) {
  const xs = condArrays.map((c) => liveItems(c)).filter((c) => c.length);
  return xs.length ? xs.map((c) => (xs.length > 1 ? `( ${condOne(c)} )` : condOne(c))).join(' AND ') : '';
}

// ---- legacy text -> one string (SAPscript paragraph rules), trimmed
const cleanTags = (s) => s.replace(/<\(>/g, '').replace(/<\)>/g, '').replace(/<\/>/g, '').replace(/<[A-Z]\d>/g, '');
function paragraphs(lines) {
  const ps = [];
  for (const { fmt, line } of lines) {
    if (/^\/\*/.test(fmt) || /^\/:/.test(fmt)) continue;
    if (ps.length && (fmt === ' ' || fmt === '')) ps[ps.length - 1] += ` ${line.trim()}`;
    else ps.push(line);
  }
  return ps.map((p) => cleanTags(p).trim()).filter((p) => p !== '');
}
const NL = '\u000a';
function textOf(node, lang) {
  const lines = lang === 'F' && node.text.F.length ? node.text.F : node.text.E;
  const ps = paragraphs(lines);
  if (ps.some((p) => /&[A-Za-z_][A-Za-z0-9_-]*(\([A-Za-z]+\))?&/.test(p))) throw new Error(`token in terms text ${node.name}`);
  return ps.join(NL);
}

// ---- ABAP string-template tokens (source lines are limited to 255 characters, so chunks of 80 characters)
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\{/g, '\\{').replace(/\}/g, '\\}');
function tokens(text) {
  const toks = [];
  text.split(NL).forEach((p, pi) => {
    if (pi) toks.push('cl_abap_char_utilities=>newline');
    for (let i = 0; i < p.length; i += 80) toks.push(`|${esc(p.slice(i, i + 80))}|`);
  });
  return toks.length ? toks : ['||'];
}
// a chain of tokens: first on the current line, the others "&& token" on their own lines at column `col`
const chain = (toks, col) => toks.map((t, i) => (i ? `${' '.repeat(col)}&& ${t}` : t));
// E / F variants: one chain when equal, else COND string( WHEN lv_fr = abap_true THEN <F> ELSE <E> ); col = column where the expression starts
function both(node, col) {
  const e = textOf(node, 'E'); const f = textOf(node, 'F');
  if (e === f) return chain(tokens(e), col);
  const c2 = col + 7;
  const fl = chain(tokens(f), c2); const el = chain(tokens(e), c2);
  const lines = ['COND string( WHEN lv_fr = abap_true', `${' '.repeat(col + 2)}THEN ${fl[0]}`, ...fl.slice(1), `${' '.repeat(col + 2)}ELSE ${el[0]}`, ...el.slice(1)];
  lines[lines.length - 1] += ' )';
  return lines;
}

const out = [];
const add = (...l) => out.push(...l);
add('* BOLT: terms and conditions prepared for the layout (GV_TERMS_TITLE, GT_TERMS). Generated by tools/zmmcg_po_sf/terms_gen.mjs from the');
add('* legacy folders %FOLDER1 / %FOLDER2 (goods, V_FLAG = X) and %FOLDER4 (service, V_FLAG = Y); texts are the legacy texts, English and French.');
add('CLEAR: gt_terms, gv_terms_title.');
add('lv_fr = COND #( WHEN v_bsart = \'ZPOL\' OR v_bsart = \'ZPOS\' THEN abap_true     "legacy driver: French for local and service orders');
add('                 WHEN v_bsart = \'ZPOI\' THEN abap_false                          "import orders: English');
add('                 WHEN gv_langu = \'F\' THEN abap_true');
add('                 ELSE abap_false ).');

let firstTable = true;
for (const tname of ['OTHER_PO', 'SERVCE_PO']) {
  const t = find(M, (n) => n.name === tname);
  add(`${firstTable ? 'IF' : 'ELSEIF'} ${abapCond([t.cond])}.      "table ${tname}`);
  firstTable = false;
  const foot = t.children.filter((c) => c.type === 'EV')[2];
  const folders = foot.children.filter((r) => r.kind === 'SECTION' && r.sect.type === 'F' && !(r.cond.length && isDead(r.cond)));
  let firstFolder = true;
  for (const f of folders) {
    const fc = abapCond(f.cond.length ? [f.cond] : []);
    add(`  ${firstFolder ? 'IF' : 'ELSEIF'} ${fc || 'abap_true = abap_true'}.      "folder ${f.name}`);
    firstFolder = false;
    const rows = f.children.filter((c) => c.kind === 'SECTION' && !(c.cond.length && isDead(c.cond)));
    for (const r of rows) {
      const cells = r.children.filter((c) => c.kind === 'SECTION');
      const texts = (cs) => (cs ? cs.children.filter((c) => c.kind === 'TEXT' && !(c.cond.length && isDead(c.cond))) : []);
      if (r.out.lineType === 'PO_HEADER') {
        const l = both(texts(cells[0])[0], 21);
        add(`    gv_terms_title = ${l[0]}`, ...l.slice(1));
        out[out.length - 1] += '.';
        continue;
      }
      const no = texts(cells[1])[0]; const txt = texts(cells[3]);
      add('    APPEND VALUE #(');
      const ls = both(no, 13); add(`      slno = ${ls[0]}`, ...ls.slice(1));
      if (txt.length === 1 && !txt[0].cond.length) {
        const lt = txt[0].ttype === 'I' ? ['gv_term1_zpos'] : both(txt[0], 13);
        add(`      text = ${lt[0]}`, ...lt.slice(1));
      } else {
        // legacy conditions on the text node(s): COND string( WHEN <condition> THEN <text> ... )
        add('      text = COND string(');
        txt.forEach((n) => {
          const nc = abapCond(n.cond.length ? [n.cond] : []) || 'abap_true = abap_true';
          const body = n.ttype === 'I' ? ['gv_term1_zpos      "standard text ZMMCG_PO_TEXT (legacy include text)'] : both(n, 21);
          add(`               WHEN ${nc}`, `               THEN ${body[0]}`, ...body.slice(1));
        });
        add('               ELSE || )');
      }
      out[out.length - 1] += ' ) TO gt_terms.';
    }
  }
  if (!firstFolder) add('  ENDIF.');
}
add('ENDIF.');
add('');

const text = out.join('\n').split('\n').map((l) => l.replace(/\s+$/, '')).join('\n');
fs.writeFileSync(path.join(HERE, 'terms_extra.abap'), text, 'utf8');
console.log(`terms ABAP written: ${text.split('\n').length} lines`);
